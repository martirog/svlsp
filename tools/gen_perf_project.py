#!/usr/bin/env python3
"""gen_perf_project.py -- generate a multi-unit UVM-style testbench project.

The perf scenarios' UVM source is a single compilation unit (`uvm.sv`
includes everything into `uvm_pkg`), so it can't show the difference
between "the opened file's unit is compiled" and "the whole project is
compiled", or a refresh that recompiles only some units (plan.md §6.34
S0). This writes a project of many units in the shape of a real
verification codebase on top of the UVM library DB:

    common/common_pkg.sv            typedefs, enums, utility functions
    agents/agent_<k>/agent_<k>_if.sv  an interface: signals, clocking block, modports
    agents/agent_<k>/agent_<k>_pkg.sv a package `include-ing one class per .svh:
        item, config, sequence, driver, monitor, agent
    envs/env_<j>_pkg.sv             an env over a few agents, scoreboard, virtual sequence
    tests/tests_pkg.sv              one uvm_test per env
    rtl/block_<m>.sv                modules instantiating each other
    tb/tb_top.sv                    the top: interfaces, DUT, run_test
    .svlsp.json                     the project (libraryDbs = --library-db)

Every file is a pure function of its own parameters (the agent's id and
revision, ...), so two variants share byte-identical files except where
they differ on purpose -- `--variant B` is a "branch" of `--variant A`:
--change agents get a new revision (an extra field and method, a changed
driver body), one agent is removed and one added (with their env and the
file list changing too). tools/refresh_perf.py commits both into a git
repo and switches between them.

    tools/gen_perf_project.py OUT --library-db /path/uvm.db
    tools/gen_perf_project.py OUT --agents 60 --envs 12 --variant B
"""

import argparse
import json
import random
import shutil
from pathlib import Path


def rng(*key):
    return random.Random(":".join(map(str, key)))


# ---------------------------------------------------------------- common

def common_pkg(n_funcs):
    out = ["// Generated by tools/gen_perf_project.py -- do not edit.", "",
           "package common_pkg;", "",
           "  typedef enum logic [1:0] {MODE_IDLE, MODE_RUN, MODE_HALT, MODE_ERR} mode_e;",
           "  typedef logic [31:0] word_t;",
           "  typedef struct packed {",
           "    logic [7:0]  tag;",
           "    logic [23:0] payload;",
           "  } frame_t;",
           "  parameter int unsigned COMMON_DEPTH = 16;", ""]
    for i in range(n_funcs):
        out += [f"  function automatic word_t common_mix_{i}(word_t a, word_t b, int unsigned rot = {i % 7 + 1});",
                f"    word_t r = a ^ (b << rot);",
                f"    for (int k = 0; k < {i % 4 + 2}; k++) r = r + (b >> k);",
                f"    return r;",
                f"  endfunction", ""]
    out += ["  class common_stats extends uvm_pkg::uvm_object;",
            "    int unsigned hits;",
            "    int unsigned misses;",
            "    `uvm_object_utils(common_stats)",
            "    function new(string name = \"common_stats\");",
            "      super.new(name);",
            "    endfunction",
            "    function void record(bit hit);",
            "      if (hit) hits++; else misses++;",
            "    endfunction",
            "  endclass", "",
            "endpackage", ""]
    return "\n".join(out[:3] + ["  `include \"uvm_macros.svh\"", ""] + out[3:])


# ---------------------------------------------------------------- agents

def agent_if(k, width):
    a = f"agent_{k}"
    return f"""// Generated by tools/gen_perf_project.py -- do not edit.

interface {a}_if (input logic clk, input logic rst_n);
  logic             valid;
  logic             ready;
  logic [{width - 1}:0]      data;
  logic [3:0]       id;
  logic             last;

  clocking drv_cb @(posedge clk);
    output valid, data, id, last;
    input  ready;
  endclocking

  clocking mon_cb @(posedge clk);
    input valid, ready, data, id, last;
  endclocking

  modport drv (clocking drv_cb, input rst_n);
  modport mon (clocking mon_cb, input rst_n);
endinterface
"""


def agent_files(k, rev, n_fields, n_seqs):
    """{relative name: text} for agent k's package and its class headers."""
    a = f"agent_{k}"
    r = rng("agent", k, rev)
    fields = [(f"f_{i}", r.choice(["int unsigned", "bit [7:0]", "bit [15:0]", "logic [31:0]",
                                   "common_pkg::word_t", "common_pkg::mode_e"]))
              for i in range(n_fields + (1 if rev else 0))]
    hdr = "// Generated by tools/gen_perf_project.py -- do not edit.\n\n"
    files = {}

    item = [hdr + f"class {a}_item extends uvm_sequence_item;"]
    item += [f"  rand {t} {n};" for n, t in fields]
    item += ["  rand bit [3:0] id;", "  bit last;", ""]
    item += [f"  constraint c_{n} {{ {n} < {r.randint(8, 200)}; }}"
             for n, t in fields if "mode_e" not in t][:4]
    item += ["", f"  `uvm_object_utils({a}_item)", "",
             f"  function new(string name = \"{a}_item\");",
             "    super.new(name);", "  endfunction", "",
             "  function void do_copy(uvm_object rhs);",
             f"    {a}_item that;",
             "    super.do_copy(rhs);",
             "    if (!$cast(that, rhs)) return;"]
    item += [f"    {n} = that.{n};" for n, _ in fields]
    item += ["  endfunction", "",
             "  function bit do_compare(uvm_object rhs, uvm_comparer comparer);",
             f"    {a}_item that;",
             "    if (!$cast(that, rhs)) return 0;",
             "    return " + " && ".join(f"{n} == that.{n}" for n, _ in fields) + ";",
             "  endfunction", "",
             "  function string convert2string();",
             "    return $sformatf(\"id=%0d" + "".join(f" {n}=%0h" for n, _ in fields) + "\", id"
             + "".join(f", {n}" for n, _ in fields) + ");",
             "  endfunction"]
    if rev:
        item += ["", f"  function int unsigned weight_r{rev}(int unsigned scale = 2);",
                 f"    return (f_0 + {rev}) * scale;", "  endfunction"]
    item += ["endclass", ""]
    files[f"{a}_item.svh"] = "\n".join(item)

    files[f"{a}_config.svh"] = hdr + f"""class {a}_config extends uvm_object;
  virtual {a}_if.drv drv_vif;
  virtual {a}_if.mon mon_vif;
  uvm_active_passive_enum is_active = UVM_ACTIVE;
  int unsigned max_burst = {r.randint(4, 64)};
  common_pkg::mode_e mode = common_pkg::MODE_RUN;

  `uvm_object_utils({a}_config)

  function new(string name = "{a}_config");
    super.new(name);
  endfunction
endclass
"""

    seqs = []
    for s in range(n_seqs):
        seqs.append(f"""class {a}_seq_{s} extends uvm_sequence #({a}_item);
  rand int unsigned count;
  constraint c_count {{ count inside {{[1:{r.randint(4, 32)}]}}; }}

  `uvm_object_utils({a}_seq_{s})

  function new(string name = "{a}_seq_{s}");
    super.new(name);
  endfunction

  task body();
    {a}_item req;
    repeat (count) begin
      req = {a}_item::type_id::create("req");
      start_item(req);
      if (!req.randomize() with {{ id == {s % 16}; }})
        `uvm_error("SEQ", "randomize failed")
      finish_item(req);
    end
  endtask
endclass
""")
    files[f"{a}_seqs.svh"] = hdr + "\n".join(seqs)

    body = (["      vif.drv_cb.data  <= req.f_0;", "      vif.drv_cb.valid <= 1;"]
            if not rev else
            ["      vif.drv_cb.data  <= req.f_0 + req.weight_r%d();" % rev,
             "      vif.drv_cb.valid <= req.id != 0;"])
    files[f"{a}_driver.svh"] = hdr + f"""class {a}_driver extends uvm_driver #({a}_item);
  virtual {a}_if.drv vif;
  {a}_config cfg;

  `uvm_component_utils({a}_driver)

  function new(string name, uvm_component parent);
    super.new(name, parent);
  endfunction

  function void build_phase(uvm_phase phase);
    super.build_phase(phase);
    if (!uvm_config_db #({a}_config)::get(this, "", "cfg", cfg))
      `uvm_fatal("NOCFG", "no config")
    vif = cfg.drv_vif;
  endfunction

  task run_phase(uvm_phase phase);
    forever begin
      seq_item_port.get_next_item(req);
      @(vif.drv_cb);
{chr(10).join(body)}
      vif.drv_cb.id    <= req.id;
      while (!vif.drv_cb.ready) @(vif.drv_cb);
      vif.drv_cb.valid <= 0;
      seq_item_port.item_done();
    end
  endtask
endclass
"""

    files[f"{a}_monitor.svh"] = hdr + f"""class {a}_monitor extends uvm_monitor;
  virtual {a}_if.mon vif;
  uvm_analysis_port #({a}_item) ap;
  common_pkg::common_stats stats;

  `uvm_component_utils({a}_monitor)

  function new(string name, uvm_component parent);
    super.new(name, parent);
    ap = new("ap", this);
  endfunction

  function void build_phase(uvm_phase phase);
    {a}_config cfg;
    super.build_phase(phase);
    if (!uvm_config_db #({a}_config)::get(this, "", "cfg", cfg))
      `uvm_fatal("NOCFG", "no config")
    vif = cfg.mon_vif;
    stats = common_pkg::common_stats::type_id::create("stats");
  endfunction

  task run_phase(uvm_phase phase);
    {a}_item tr;
    forever begin
      @(vif.mon_cb);
      if (vif.mon_cb.valid && vif.mon_cb.ready) begin
        tr = {a}_item::type_id::create("tr");
        tr.id = vif.mon_cb.id;
        tr.last = vif.mon_cb.last;
        stats.record(tr.last);
        ap.write(tr);
      end
    end
  endtask
endclass
"""

    extra = (f"""
  function int unsigned burst_r{rev}();
    return cfg.max_burst + {rev};
  endfunction
""" if rev else "")
    files[f"{a}_agent.svh"] = hdr + f"""typedef uvm_sequencer #({a}_item) {a}_sequencer;

class {a}_agent extends uvm_agent;
  {a}_config    cfg;
  {a}_driver    drv;
  {a}_monitor   mon;
  {a}_sequencer sqr;

  `uvm_component_utils({a}_agent)

  function new(string name, uvm_component parent);
    super.new(name, parent);
  endfunction

  function void build_phase(uvm_phase phase);
    super.build_phase(phase);
    if (!uvm_config_db #({a}_config)::get(this, "", "cfg", cfg))
      `uvm_fatal("NOCFG", "no config")
    mon = {a}_monitor::type_id::create("mon", this);
    if (cfg.is_active == UVM_ACTIVE) begin
      drv = {a}_driver::type_id::create("drv", this);
      sqr = {a}_sequencer::type_id::create("sqr", this);
    end
  endfunction

  function void connect_phase(uvm_phase phase);
    if (cfg.is_active == UVM_ACTIVE)
      drv.seq_item_port.connect(sqr.seq_item_export);
  endfunction
{extra}endclass
"""

    order = ["item", "config", "seqs", "driver", "monitor", "agent"]
    files[f"{a}_pkg.sv"] = hdr + f"package {a}_pkg;\n  import uvm_pkg::*;\n" \
        "  `include \"uvm_macros.svh\"\n" + \
        "".join(f"  `include \"{a}_{o}.svh\"\n" for o in order) + "endpackage\n"
    return files


# ---------------------------------------------------------------- envs, tests, rtl, top

def env_pkg(j, agents):
    e = f"env_{j}"
    hdr = "// Generated by tools/gen_perf_project.py -- do not edit.\n\n"
    imports = "".join(f"  import agent_{k}_pkg::*;\n" for k in agents)
    decls = "".join(f"  agent_{k}_agent ag_{k};\n" for k in agents)
    imps = "".join(f"`uvm_analysis_imp_decl(_{e}_{k})\n" for k in agents)
    sb_ports = "".join(f"  uvm_analysis_imp_{e}_{k} #(agent_{k}_pkg::agent_{k}_item, {e}_scoreboard) imp_{k};\n"
                       for k in agents)
    sb_new = "".join(f"    imp_{k} = new(\"imp_{k}\", this);\n" for k in agents)
    sb_writes = "".join(f"""  function void write_{e}_{k}(agent_{k}_pkg::agent_{k}_item t);
    seen++;
    if (t.last) `uvm_info("SB", t.convert2string(), UVM_HIGH)
  endfunction
""" for k in agents)
    build = "".join(f"    ag_{k} = agent_{k}_agent::type_id::create(\"ag_{k}\", this);\n" for k in agents)
    connect = "".join(f"    ag_{k}.mon.ap.connect(sb.imp_{k});\n" for k in agents)
    vseq_decl = "".join(f"  agent_{k}_sequencer sqr_{k};\n" for k in agents)
    vseq_body = "".join(f"""      begin
        agent_{k}_seq_0 s = agent_{k}_seq_0::type_id::create("s_{k}");
        if (!s.randomize()) `uvm_error("VSEQ", "randomize failed")
        s.start(sqr_{k});
      end
""" for k in agents)
    return hdr + f"""package {e}_pkg;
  import uvm_pkg::*;
  `include "uvm_macros.svh"
{imports}
{imps}
class {e}_scoreboard extends uvm_scoreboard;
{sb_ports}  int unsigned seen;

  `uvm_component_utils({e}_scoreboard)

  function new(string name, uvm_component parent);
    super.new(name, parent);
{sb_new}  endfunction

{sb_writes}  function void report_phase(uvm_phase phase);
    `uvm_info("SB", $sformatf("seen %0d", seen), UVM_LOW)
  endfunction
endclass

class {e}_vseq extends uvm_sequence;
{vseq_decl}
  `uvm_object_utils({e}_vseq)

  function new(string name = "{e}_vseq");
    super.new(name);
  endfunction

  task body();
    fork
{vseq_body}    join
  endtask
endclass

class {e} extends uvm_env;
{decls}  {e}_scoreboard sb;

  `uvm_component_utils({e})

  function new(string name, uvm_component parent);
    super.new(name, parent);
  endfunction

  function void build_phase(uvm_phase phase);
    super.build_phase(phase);
{build}    sb = {e}_scoreboard::type_id::create("sb", this);
  endfunction

  function void connect_phase(uvm_phase phase);
{connect}  endfunction
endclass
endpackage
"""


def tests_pkg(envs):
    hdr = "// Generated by tools/gen_perf_project.py -- do not edit.\n\n"
    imports = "".join(f"  import env_{j}_pkg::*;\n" for j, _ in envs)
    tests = []
    for j, agents in envs:
        sqrs = "".join(f"    vseq.sqr_{k} = env.ag_{k}.sqr;\n" for k in agents)
        tests.append(f"""class test_{j} extends uvm_test;
  env_{j} env;

  `uvm_component_utils(test_{j})

  function new(string name, uvm_component parent);
    super.new(name, parent);
  endfunction

  function void build_phase(uvm_phase phase);
    super.build_phase(phase);
    env = env_{j}::type_id::create("env", this);
  endfunction

  task run_phase(uvm_phase phase);
    env_{j}_vseq vseq = env_{j}_vseq::type_id::create("vseq");
    phase.raise_objection(this);
{sqrs}    vseq.start(null);
    phase.drop_objection(this);
  endtask
endclass
""")
    return hdr + "package tests_pkg;\n  import uvm_pkg::*;\n  `include \"uvm_macros.svh\"\n" \
        + imports + "\n" + "\n".join(tests) + "endpackage\n"


def rtl_block(m, n_blocks, width):
    r = rng("rtl", m)
    hdr = "// Generated by tools/gen_perf_project.py -- do not edit.\n\n"
    kids = [c for c in (2 * m + 1, 2 * m + 2) if c < n_blocks]
    insts = "".join(f"""  block_{c} #(.W(W)) u_block_{c} (
    .clk(clk), .rst_n(rst_n),
    .in_data(stage[{i}]), .in_valid(valid_q),
    .out_data(kid_data[{i}]), .out_valid(kid_valid[{i}])
  );
""" for i, c in enumerate(kids))
    n = max(len(kids), 1)
    regs = "".join(f"  logic [W-1:0] r_{i};\n" for i in range(r.randint(3, 8)))
    return hdr + f"""module block_{m} #(parameter int W = {width}) (
  input  logic         clk,
  input  logic         rst_n,
  input  logic [W-1:0] in_data,
  input  logic         in_valid,
  output logic [W-1:0] out_data,
  output logic         out_valid
);
  logic [W-1:0] stage [{n}];
  logic [W-1:0] kid_data [{n}];
  logic         kid_valid [{n}];
  logic         valid_q;
{regs}
  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      valid_q <= 1'b0;
      for (int i = 0; i < {n}; i++) stage[i] <= '0;
    end else begin
      valid_q <= in_valid;
      for (int i = 0; i < {n}; i++) stage[i] <= in_data ^ W'(i * {r.randint(1, 99)});
    end
  end

{insts}  assign out_data  = {"kid_data[0]" if kids else "stage[0]"};
  assign out_valid = {"kid_valid[0]" if kids else "valid_q"};
endmodule
"""


def tb_top(agent_ids, width):
    hdr = "// Generated by tools/gen_perf_project.py -- do not edit.\n\n"
    ifs = "".join(f"  agent_{k}_if if_{k} (.clk(clk), .rst_n(rst_n));\n" for k in agent_ids)
    cfgs = "".join(f"""    begin
      agent_{k}_pkg::agent_{k}_config c = new("cfg_{k}");
      c.drv_vif = if_{k};
      c.mon_vif = if_{k};
      uvm_config_db #(agent_{k}_pkg::agent_{k}_config)::set(null, "*ag_{k}*", "cfg", c);
    end
""" for k in agent_ids)
    return hdr + f"""module tb_top;
  import uvm_pkg::*;
  import tests_pkg::*;

  logic clk = 0;
  logic rst_n = 0;
  logic [{width - 1}:0] dut_out;
  logic dut_valid;

  always #5 clk = ~clk;

{ifs}
  block_0 u_dut (
    .clk(clk), .rst_n(rst_n),
    .in_data(if_{agent_ids[0]}.data), .in_valid(if_{agent_ids[0]}.valid),
    .out_data(dut_out), .out_valid(dut_valid)
  );

  initial begin
{cfgs}    #20 rst_n = 1;
    run_test();
  end
endmodule
"""


# ---------------------------------------------------------------- the project

def layout(args):
    """(agent ids with their revision, envs as (id, agent ids))."""
    ids = list(range(args.agents))
    revs = {k: 0 for k in ids}
    if args.variant == "B":
        r = rng("variant-B", args.agents)
        changed = r.sample(ids, max(1, round(args.agents * args.change)))
        for k in changed:
            revs[k] = 1
        # One agent removed (the last one, in the last env only) and one added.
        removed = ids[-1]
        del revs[removed]
        revs[args.agents] = 0
    per_env = max(1, -(-args.agents // args.envs))
    envs = []
    for j in range(args.envs):
        members = [k for k in range(j * per_env, (j + 1) * per_env) if k in revs]
        if j == args.envs - 1 and args.variant == "B":
            members.append(args.agents)  # the added agent joins the last env
        if members:
            envs.append((j, members))
    return revs, envs


def generate(args):
    out = Path(args.out)
    for sub in ("common", "agents", "envs", "tests", "rtl", "tb"):
        shutil.rmtree(out / sub, ignore_errors=True)
    out.mkdir(parents=True, exist_ok=True)
    revs, envs = layout(args)

    def write(rel, text):
        p = out / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)

    files, include_dirs = ["common/common_pkg.sv"], []
    write("common/common_pkg.sv", common_pkg(args.funcs))
    for k, rev in sorted(revs.items()):
        d = f"agents/agent_{k}"
        include_dirs.append(d)
        write(f"{d}/agent_{k}_if.sv", agent_if(k, args.width))
        for name, text in agent_files(k, rev, args.fields, args.seqs).items():
            write(f"{d}/{name}", text)
        files += [f"{d}/agent_{k}_if.sv", f"{d}/agent_{k}_pkg.sv"]
    for j, agents in envs:
        write(f"envs/env_{j}_pkg.sv", env_pkg(j, agents))
        files.append(f"envs/env_{j}_pkg.sv")
    write("tests/tests_pkg.sv", tests_pkg(envs))
    files.append("tests/tests_pkg.sv")
    for m in range(args.rtl):
        write(f"rtl/block_{m}.sv", rtl_block(m, args.rtl, args.width))
        files.append(f"rtl/block_{m}.sv")
    write("tb/tb_top.sv", tb_top(sorted(revs), args.width))
    files.append("tb/tb_top.sv")

    config = {"files": files, "includeDirs": include_dirs}
    if args.library_db:
        config["libraryDbs"] = [args.library_db]
    (out / ".svlsp.json").write_text(json.dumps(config, indent=2) + "\n")
    lines = sum(len(p.read_text().splitlines()) for p in out.rglob("*.sv*") if p.is_file())
    return len(files), lines


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("out", help="directory to write (its generated subdirectories are replaced)")
    ap.add_argument("--library-db", help="the UVM library DB the project attaches")
    ap.add_argument("--agents", type=int, default=40)
    ap.add_argument("--envs", type=int, default=8)
    ap.add_argument("--fields", type=int, default=8, help="fields per sequence item")
    ap.add_argument("--seqs", type=int, default=4, help="sequences per agent")
    ap.add_argument("--funcs", type=int, default=20, help="functions in common_pkg")
    ap.add_argument("--rtl", type=int, default=31, help="RTL blocks (a binary tree)")
    ap.add_argument("--width", type=int, default=32)
    ap.add_argument("--variant", choices=["A", "B"], default="A")
    ap.add_argument("--change", type=float, default=0.1,
                    help="variant B: the fraction of agents that get a new revision")
    args = ap.parse_args()
    n, lines = generate(args)
    print(f"gen_perf_project: {args.out}: {n} project files, {lines} lines (variant {args.variant})")


if __name__ == "__main__":
    main()
